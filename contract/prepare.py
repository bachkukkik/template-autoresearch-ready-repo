"""prepare.py — the immutable anti-cheat evaluator of the autoresearch loop.

Do NOT edit this file (see program.md, section *Experimentation*). It owns the
fixed constants, the corpus, the tokenizer, the dataloader, the ground-truth
metric `evaluate_bpb`, the keep/discard `decide()` rule, and the ledger checker
`check_ledger()`. The agent's only job is to make `val_bpb` as low as possible by
editing ONLY train.py, and train.py must import evaluate_bpb from here, never
redefine it.

SC5 (domain adaptation): to port this template to a new domain, change only the
DATA section below (corpus constants + tokenizer + dataloader) and the notes in
program.md. The metric and the loop stay intact.

Stdlib only — no numpy, no torch.
"""

import argparse
import math
import os
import sys

# ---------------------------------------------------------------------------
# Fixed constants
# ---------------------------------------------------------------------------
TIME_BUDGET = 300  # seconds — fixed wall-clock training budget (SC2, SC6)
MAX_SEQ_LEN = 32
BATCH_SIZE = 16

# ---------------------------------------------------------------------------
# Decision policy — evaluator-owned (SC2, SC8)
# ---------------------------------------------------------------------------
# The keep/discard rule lives here, not in train.py: the agent proposes, the
# evaluator decides. DIRECTION names which way "better" points, so the same
# contract ports to a higher-is-better metric unchanged. NOISE_FLOOR is a
# relative epsilon: a metric move inside it is not signal, so it is only worth
# a keep when the artifact also shrinks (the simplicity criterion).
DIRECTION = "lower"
NOISE_FLOOR = 0.001
LEDGER_HEADER = "commit\tval_bpb\tmemory_gb\tstatus\tdescription"
LEDGER_STATUSES = ("keep", "discard", "crash")

# ---------------------------------------------------------------------------
# Data side — the ONLY section that changes when porting to a new domain (SC5)
# ---------------------------------------------------------------------------
# A tiny deterministic char-level corpus: enough structure for a meaningful
# val_bpb baseline, small enough to train in milliseconds under any budget.
TRAIN_TEXT = (
    "the quick brown fox jumps over the lazy dog. "
    "pack my box with five dozen liquor jugs. "
    "how vexingly quick daft zebras jump. "
) * 60

VAL_TEXT = (
    "sphinx of black quartz judge my vow. "
    "the five boxing wizards jump quickly."
)

# Special tokens. Token id 0 = <pad> (masked in evaluation).
_PAD, _BOS, _EOS = 0, 1, 2
SPECIAL_TOKENS = {"<pad>": _PAD, "<bos>": _BOS, "<eos>": _EOS}
MASK_IDS = frozenset((_PAD,))  # special tokens are masked in the metric


def _char_tokens(text):
    """Split a string into single-character tokens (char-level model)."""
    return list(text)


def tokenizer():
    """SC5 data hook — the (vocab, tokenize) pair for the domain.

    Returns:
        vocab:    list of token strings; index i is token id i.
        tokenize: callable text -> list[int] (token ids).
    """
    specials = [tok for tok in SPECIAL_TOKENS]
    chars = sorted({c for c in TRAIN_TEXT + VAL_TEXT})
    vocab = specials + chars
    index = {tok: i for i, tok in enumerate(vocab)}

    def tokenize(text):
        return [index[tok] for tok in _char_tokens(text)]

    return vocab, tokenize


# Token id -> utf-8 byte length. Built once (ASCII char corpus => 1 byte each).
VOCAB, TOKENIZE = tokenizer()
TOKEN_BYTES = {i: len(tok.encode("utf-8")) for i, tok in enumerate(VOCAB)}


def dataloader(text, batch_size=BATCH_SIZE, seq_len=MAX_SEQ_LEN):
    """SC5 data hook — yield (x_ids, y_ids) batches for a corpus string.

    Sliding-window char n-grams: x is a context window, y is the shifted
    target window. Yields batches of (list[int], list[int]) pairs.
    """
    ids = TOKENIZE(text)
    windows = []
    for i in range(len(ids) - seq_len):
        x = ids[i:i + seq_len]
        y = ids[i + 1:i + 1 + seq_len]
        windows.append((x, y))
    for start in range(0, len(windows), batch_size):
        yield windows[start:start + batch_size]


def _byte_len(token_bytes, token_id) -> int:
    """Resolve the utf-8 byte length of a token id (mapping or callable)."""
    if callable(token_bytes):
        return int(token_bytes(token_id))
    return int(token_bytes[token_id])


def evaluate_bpb(logits, target_ids, token_bytes, mask_ids=MASK_IDS):
    """Ground-truth metric (SC4): bits per byte over a validation batch.

        total per-token cross-entropy in nats
    -------------------------------------------------
        log(2) x total utf-8 byte length of targets

    Special tokens (mask_ids) are excluded from both the numerator and the
    byte-length denominator. Lower is better. This is the metric train.py must
    minimise — it is the anti-cheat ground truth and must never be redefined.

    Args:
        logits:      iterable of per-position logit vectors (len V each).
        target_ids:  iterable of target token ids (same length as logits).
        token_bytes: mapping {token_id: byte_length} or callable id -> length.
        mask_ids:    frozenset of special token ids to mask.
    """
    if len(logits) != len(target_ids):
        raise ValueError(
            "evaluate_bpb: logits and target_ids must have equal length, "
            "got {} and {}".format(len(logits), len(target_ids)))
    total_nats = 0.0
    total_bytes = 0
    for lg, tid in zip(logits, target_ids):
        if tid in mask_ids:
            continue
        # numerically-safe softmax over the position's logits
        m = max(lg)
        exp_sum = 0.0
        for x in lg:
            exp_sum += math.exp(x - m)
        p_target = math.exp(lg[tid] - m) / exp_sum
        total_nats += -math.log(p_target)
        total_bytes += _byte_len(token_bytes, tid)
    if total_bytes <= 0:
        raise ValueError("evaluate_bpb: no countable target bytes (all masked?)")
    return total_nats / (math.log(2.0) * total_bytes)


def decide(metric, incumbent, epsilon=NOISE_FLOOR, direction=DIRECTION,
           shrinks=False):
    """Evaluator-owned keep/discard decision (SC8) — the agent never self-awards.

    Args:
        metric:    the candidate's measured value (read from the run log).
        incumbent: the best `keep` value so far, or None for the baseline run.
        epsilon:   relative noise floor; a move inside it is not signal.
        direction: "lower" or "higher" — which way is better.
        shrinks:   True when the candidate artifact is smaller than the incumbent
                   (the simplicity criterion: a within-noise-floor tie is only
                   worth keeping when the code also shrank).

    Returns:
        "keep" or "discard". A strict improvement beyond `epsilon` is a keep; a
        move inside `epsilon` is a keep only when `shrinks`, else a discard; no
        incumbent (the first, baseline run) is always a keep.
    """
    if incumbent is None:
        return "keep"  # baseline: nothing to beat yet
    if direction not in ("lower", "higher"):
        raise ValueError("decide: direction must be 'lower' or 'higher', "
                         "got {!r}".format(direction))
    if direction == "lower":
        improved = metric < incumbent * (1.0 - epsilon)
        within = metric <= incumbent * (1.0 + epsilon)
    else:
        improved = metric > incumbent * (1.0 + epsilon)
        within = metric >= incumbent * (1.0 - epsilon)
    if improved:
        return "keep"
    if within and shrinks:
        return "keep"  # no worse beyond noise AND simpler
    return "discard"


def check_ledger(path):
    """Validate an append-only results ledger (SC9); return the violations.

    The ledger is the run's only durable record, so it is checked, not trusted.
    Enforced: the exact header, 5 tab-separated columns, a 7-char commit, the
    status vocabulary, crash rows at 0.000000/0.000, a keep baseline first, and
    every later `keep` consistent with `decide` against the prior best keep
    (a worse candidate may never be recorded as a keep).

    Returns:
        list[str] of human-readable violations; empty means the ledger is valid.
    """
    if not path or not os.path.exists(path):
        return ["{}: missing (no ledger to check)".format(path)]
    violations = []
    with open(path) as f:
        lines = f.read().splitlines()
    if not lines:
        return ["{}: empty ledger".format(path)]
    if lines[0] != LEDGER_HEADER:
        violations.append(
            "header mismatch: expected {!r}, got {!r}".format(
                LEDGER_HEADER, lines[0]))

    data_rows = lines[1:]
    if not data_rows:
        violations.append(
            "no data rows: the ledger must record at least the baseline")
    incumbent = None
    for i, line in enumerate(data_rows, start=1):
        cols = line.split("\t")
        where = "row {} ({!r})".format(i, line)
        if len(cols) != 5:
            violations.append("{}: expected 5 tab-separated columns, got {}".format(
                where, len(cols)))
            continue
        commit, val_bpb, memory_gb, status, _desc = cols
        if len(commit) != 7:
            violations.append("{}: commit {!r} is not 7 chars".format(where, commit))
        if status not in LEDGER_STATUSES:
            violations.append("{}: status {!r} not in {}".format(
                where, status, list(LEDGER_STATUSES)))
        try:
            metric = float(val_bpb)
            memory = float(memory_gb)
        except ValueError:
            violations.append("{}: val_bpb/memory_gb are not floats".format(where))
            continue
        if i == 1 and status != "keep":
            violations.append(
                "{}: the first data row is the baseline and must be 'keep', "
                "got {!r}".format(where, status))
        if status == "crash":
            if metric != 0.0 or memory != 0.0:
                violations.append(
                    "{}: crash row must carry 0.000000/0.000, got {}/{}".format(
                        where, val_bpb, memory_gb))
            continue
        if status == "keep":
            flagged = False
            if incumbent is not None and decide(metric, incumbent,
                                                shrinks=True) != "keep":
                flagged = True
                violations.append(
                    "{}: keep of {} is worse than the incumbent {} beyond the "
                    "noise floor ({}). The evaluator decides keep/discard — "
                    "re-derive the row with prepare.decide".format(
                        where, metric, incumbent, NOISE_FLOOR))
            # Only a valid keep advances the incumbent: a bad keep must not
            # mask later bad keeps (each is judged against the prior best).
            if not flagged:
                incumbent = metric
    return violations


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Frozen autoresearch evaluator — dataset summary, or a "
                    "results.tsv ledger check.")
    parser.add_argument(
        "--check-ledger", default=None, metavar="PATH",
        help="validate a results.tsv ledger; exit 0 valid / 1 violations")
    args = parser.parse_args()
    if args.check_ledger is not None:
        found = check_ledger(args.check_ledger)
        for violation in found:
            print("LEDGER: " + violation)
        if found:
            print("check-ledger FAILED — {} violation(s)".format(len(found)))
            sys.exit(1)
        print("check-ledger OK")
        sys.exit(0)
    v, tok = tokenizer()
    print("prepare.py OK — TIME_BUDGET={}s, vocab_size={}".format(TIME_BUDGET, len(v)))
