"""Unit tier — engine-backed operations on REST and MCP (PRD-20 SC3/SC4).

IDs: AC-SVC-010..016 (dual registration, replay run, report, refusals, research
via the engine, per-job repo, cancel) and AC-SVC-020..024 (agent allowlist,
`command` refused, replay-record shape, no host-path workloads).

Hermetic: importing ``autoresearch_service.main`` runs ``create_app()``, so the
job database and the workspaces root are pointed at temp dirs BEFORE the import
(test_routes.py pattern). The replay patches are real: they are generated by
``git diff`` against a temp copy of the bundled contract, so the engine applies
them exactly as it would a recorded run.
"""

import asyncio
import json
import os
import shutil
import subprocess
import tempfile
import time
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
CONTRACT = REPO_ROOT / "autoresearch" / "contract"

_SCRATCH = Path(tempfile.mkdtemp(prefix="ar-unit-engine-"))
os.environ["RESEARCH_JOBS_DB"] = str(_SCRATCH / "jobs.db")
os.environ["RESEARCH_WORKSPACES_DIR"] = str(_SCRATCH / "workspaces")
os.environ["RESEARCH_RUN_TIMEOUT"] = "30"
os.environ["AUTH_DISABLED"] = "1"
os.environ.pop("RESEARCH_ALLOWED_AGENTS", None)

from fastapi.testclient import TestClient  # noqa: E402

from autoresearch_service import main, policy, workspace, workloads  # noqa: E402

TERMINAL = ("completed", "failed", "cancelled", "timeout")


@pytest.fixture(scope="module")
def client():
    """One TestClient for the module, so its lifespan starts the scheduler once.

    ``autoresearch_service.auth`` reads its two switches once, at import: if an
    earlier test module (test_routes.py) imported it first, this module's
    ``AUTH_DISABLED=1`` never reached it and every request would 401. The bearer
    layer has its own tests (tests/unit/test_auth.py), so it is switched off here
    explicitly and restored afterwards — no production code involved.
    """
    import autoresearch_service.auth as auth

    previous = (auth.AUTH_TOKEN, auth.AUTH_DISABLED)
    auth.AUTH_TOKEN, auth.AUTH_DISABLED = None, True
    # A fresh app = a fresh store and a fresh scheduler: the module-level app's
    # scheduler has already been shut down by whoever ran a TestClient earlier
    # (APScheduler's executor pool does not survive shutdown), which would leave
    # every queued job unexecuted.
    app = main.create_app()
    try:
        with TestClient(app) as test_client:
            yield test_client
    finally:
        auth.AUTH_TOKEN, auth.AUTH_DISABLED = previous


def _replay_records(count: int = 2) -> list:
    """Build replay records whose patches edit train.py, via a real git diff."""
    work = Path(tempfile.mkdtemp(prefix="ar-patch-", dir=_SCRATCH))
    for name in ("prepare.py", "train.py", "program.md"):
        shutil.copy2(CONTRACT / name, work / name)

    def git(*args: str) -> str:
        return subprocess.run(
            ["git", *args],
            cwd=work,
            capture_output=True,
            text=True,
            timeout=60,
            check=True,
        ).stdout

    git("init", "-b", "main")
    git("add", "-A")
    git(
        "-c",
        "user.name=test",
        "-c",
        "user.email=test@localhost",
        "commit",
        "--no-verify",
        "-m",
        "baseline",
    )
    source = (work / "train.py").read_text(encoding="utf-8")
    (work / "train.py").write_text(
        source.replace("STEP_WINDOW = 256", "STEP_WINDOW = 64"), encoding="utf-8"
    )
    patch = git("diff")
    assert patch.strip(), "the generated replay patch is empty"
    return [
        {"iteration": iteration, "description": f"window {iteration}", "patch": patch}
        for iteration in range(1, count + 1)
    ]


def _wait(client, path: str, max_seconds: float = 120.0) -> dict:
    """Poll a job endpoint until its status is terminal."""
    deadline = time.monotonic() + max_seconds
    body = {}
    while time.monotonic() < deadline:
        response = client.get(path)
        assert response.status_code == 200, response.text
        body = response.json()
        if body["status"] in TERMINAL:
            return body
        time.sleep(0.2)
    raise AssertionError(f"{path} never reached a terminal status (last: {body})")


def _start_run(client, **body) -> dict:
    """POST /api/v1/runs and return the created job dict."""
    payload = {"workload": "contract", "agent": "replay"}
    payload.update(body)
    response = client.post("/api/v1/runs", json=payload)
    assert response.status_code == 202, response.text
    job = response.json()
    assert job["status"] == "queued"
    return job


# ─── AC-SVC-010: one handler, both surfaces ─────────────────────────────────


def test_run_operations_are_one_handler_on_rest_and_mcp(client, monkeypatch):
    """AC-SVC-010: run_start/status/report/cancel and doctor are MCP tools whose
    function is the module-level handler, and the REST routes reach that same
    handler (proved by substituting it and seeing the request arrive)."""
    tools = {tool.name: tool for tool in asyncio.run(main.mcp.list_tools())}
    for operation in ("run_start", "run_status", "run_report", "run_cancel", "doctor"):
        assert operation in tools, f"{operation} is not registered as an MCP tool"
        assert tools[operation].fn is getattr(main, operation), (
            f"{operation}'s MCP tool is not the module-level handler"
        )

    calls = []

    def fake_doctor():
        calls.append("doctor")
        return {"allowed_agents": ["replay"]}

    monkeypatch.setattr(main, "doctor", fake_doctor)
    assert client.get("/api/v1/doctor").json() == {"allowed_agents": ["replay"]}
    assert calls == ["doctor"]

    monkeypatch.setattr(
        main, "run_start", lambda **kwargs: calls.append(kwargs) or {"id": "x", "status": "queued"}
    )
    response = client.post("/api/v1/runs", json={"workload": "contract", "agent": "replay"})
    assert response.status_code == 202
    assert calls[-1]["agent"] == "replay"


# ─── AC-SVC-011 / 012: a real replay run and its report ─────────────────────


def test_replay_run_completes_with_engine_summary(client):
    """AC-SVC-011: a replay run over the bundled contract completes, and the
    status carries the engine's summary — numeric baseline, one trial per
    iteration, a stop reason."""
    job = _start_run(
        client, max_iterations=2, records=_replay_records(2), idempotency_key="svc-011"
    )
    done = _wait(client, f"/api/v1/runs/{job['id']}")

    assert done["status"] == "completed"
    assert done["result"]["exit_code"] == 0
    engine = done["engine"]
    assert engine["metric_name"] == "val_bpb"
    assert isinstance(engine["baseline_metric"], float)
    assert 3.0 < engine["baseline_metric"] < 4.5  # the contract's bigram baseline
    assert engine["trials"] == 2  # one trial per iteration attempted
    assert sum(engine["outcomes"].values()) == 2
    assert engine["stop_reason"] == "max_iterations"


def test_report_returns_engine_markdown_and_rows(client):
    """AC-SVC-012: GET /report returns the engine's report markdown (naming the
    metric) plus its results rows, baseline included."""
    job = _start_run(
        client, max_iterations=1, records=_replay_records(1), idempotency_key="svc-012"
    )
    _wait(client, f"/api/v1/runs/{job['id']}")

    response = client.get(f"/api/v1/runs/{job['id']}/report")
    assert response.status_code == 200
    body = response.json()
    assert body["job_id"] == job["id"]
    assert body["status"] == "completed"
    assert "val_bpb" in body["report"]
    assert "## Trials" in body["report"]
    assert [row["outcome"] for row in body["results"]][0] == "baseline"
    assert len(body["results"]) == 2  # baseline + one trial


