# ─── AC-SVC-014: research_* is the engine's measurement ─────────────────────


def test_research_path_measures_through_the_engine(client, monkeypatch):
    """AC-SVC-014: research_start now takes ONE ``autoresearch.measure.measure``
    measurement (spied) and still reports a numeric val_bpb."""
    import autoresearch.measure as engine_measure

    seen = []
    real_measure = engine_measure.measure

    def spy(cfg, **kwargs):
        seen.append(cfg.verify)
        return real_measure(cfg, **kwargs)

    monkeypatch.setattr(engine_measure, "measure", spy)
    response = client.post("/api/v1/research", json={"topic": "engine measured topic"})
    assert response.status_code == 202
    done = _wait(client, f"/api/v1/research/{response.json()['id']}")

    assert done["status"] == "completed"
    assert isinstance(done["result"]["val_bpb"], float)
    assert 3.0 < done["result"]["val_bpb"] < 4.5
    assert seen, "research_* did not go through autoresearch.measure"
    assert done["result"]["topic"] == "engine measured topic"


# ─── AC-SVC-015: one git repo per job ───────────────────────────────────────


def test_each_job_gets_a_configured_git_repo_under_the_workspaces_root(client):
    """AC-SVC-015: the job's workspace is a git repo under the workspaces root,
    configured by the engine (.autoresearch/run.json), left clean."""
    response = client.post("/api/v1/research", json={"topic": "workspace layout"})
    job_id = response.json()["id"]
    _wait(client, f"/api/v1/research/{job_id}")

    repo = workspace.repo_dir(job_id)
    assert repo == workspace.DEFAULT_WORKSPACES_DIR / job_id / "repo"
    assert (repo / ".git").is_dir()

    run_json = json.loads((repo / ".autoresearch" / "run.json").read_text(encoding="utf-8"))
    spec = workloads.get_workload("contract")
    assert run_json["verify"] == spec.verify
    assert run_json["metric_name"] == "val_bpb"
    assert run_json["scope"] == ["train.py"]
    assert list(run_json["protected"]) == ["prepare.py"]  # the evaluator, not train.py

    top = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        cwd=repo,
        capture_output=True,
        text=True,
        timeout=60,
        check=True,
    ).stdout.strip()
    assert Path(top).resolve() == repo.resolve()

    status = subprocess.run(
        ["git", "status", "--porcelain", "--untracked-files=all"],
        cwd=repo,
        capture_output=True,
        text=True,
        timeout=60,
        check=True,
    ).stdout
    # The engine's state dir ignores itself; interpreter by-products are noise.
    assert [line for line in status.splitlines() if "__pycache__" not in line] == []


# ─── AC-SVC-016: cancel ─────────────────────────────────────────────────────


def test_cancel_is_terminal_and_a_late_completion_cannot_undo_it(client):
    """AC-SVC-016: cancelling a queued run reports cancelled, and the status
    stays cancelled afterwards — a terminal state wins over the worker."""
    job = _start_run(
        client, max_iterations=2, records=_replay_records(2), idempotency_key="svc-016"
    )
    response = client.delete(f"/api/v1/runs/{job['id']}")
    assert response.status_code == 200
    assert response.json()["status"] == "cancelled"

    time.sleep(1.0)
    assert client.get(f"/api/v1/runs/{job['id']}").json()["status"] == "cancelled"
    # already terminal: a second cancel returns the job unchanged
    assert client.delete(f"/api/v1/runs/{job['id']}").json()["status"] == "cancelled"


# ─── AC-SVC-020..024: safe by default ───────────────────────────────────────


def test_unlisted_harness_agent_is_refused_by_default(client, monkeypatch):
    """AC-SVC-020: with no RESEARCH_ALLOWED_AGENTS, `claude` is a 400 (nothing
    is queued) while `replay` is accepted."""
    monkeypatch.delenv("RESEARCH_ALLOWED_AGENTS", raising=False)
    assert policy.allowed_agents() == ("replay",)

    response = client.post("/api/v1/runs", json={"agent": "claude", "records": []})
    assert response.status_code == 400
    assert "not allowed" in response.json()["detail"]

    rejected = client.delete(f"/api/v1/runs/{'0' * 32}")
    assert rejected.status_code == 404  # no job was created for the refusal


def test_listed_harness_agent_passes_validation(monkeypatch):
    """AC-SVC-021: a harness listed in RESEARCH_ALLOWED_AGENTS validates.

    Validation only — the job is never executed: the image ships no harness
    binary, and a host that has one must not be driven by a unit test.
    """
    monkeypatch.setenv("RESEARCH_ALLOWED_AGENTS", "claude, opencode")
    assert policy.allowed_agents() == ("replay", "claude", "opencode")
    assert policy.validate_agent("claude") == "claude"

    params = policy.validate_run_request(
        workload="contract", agent="claude", max_iterations=1
    )
    assert params["kind"] == "run"
    assert params["agent"] == "claude"
    assert params["workload"] == "contract"


def test_command_adapter_is_refused_even_when_listed(monkeypatch):
    """AC-SVC-022: `command` runs an arbitrary shell template, so it is refused
    over the API even when the operator lists it."""
    monkeypatch.setenv("RESEARCH_ALLOWED_AGENTS", "command,claude")
    assert "command" not in policy.allowed_agents()
    with pytest.raises(ValueError, match="never available over the API"):
        policy.validate_agent("command")


def test_replay_needs_well_formed_bounded_records(client):
    """AC-SVC-023: replay without records, with malformed records, or with an
    oversized patch is a 400 — before a job exists."""
    record = {"iteration": 1, "patch": "--- a/train.py\n+++ b/train.py\n"}

    assert client.post("/api/v1/runs", json={"agent": "replay"}).status_code == 400
    assert (
        client.post("/api/v1/runs", json={"agent": "replay", "records": "nope"}).status_code
        == 400
    )
    assert (
        client.post(
            "/api/v1/runs", json={"agent": "replay", "records": [{"patch": "x"}]}
        ).status_code
        == 400
    )
    assert (
        client.post(
            "/api/v1/runs",
            json={"agent": "replay", "records": [{"iteration": 1, "patch": 5}]},
        ).status_code
        == 400
    )
    oversized = {"iteration": 1, "patch": "x" * (policy.MAX_PATCH_BYTES + 1)}
    assert (
        client.post("/api/v1/runs", json={"agent": "replay", "records": [oversized]}).status_code
        == 400
    )
    too_many = [dict(record, iteration=index) for index in range(1, policy.MAX_RECORDS + 2)]
    assert (
        client.post("/api/v1/runs", json={"agent": "replay", "records": too_many}).status_code
        == 400
    )


def test_no_field_accepts_a_host_path(client):
    """AC-SVC-024: the workload is a registry name, never a directory — a
    traversal, an absolute path and an unknown name are all 400."""
    for workload in ("../../etc", "/tmp", "/etc/passwd", "contract/../contract"):
        response = client.post("/api/v1/runs", json={"workload": workload})
        assert response.status_code == 400, workload
        assert "unknown workload" in response.json()["detail"]
    with pytest.raises(ValueError):
        workloads.get_workload("/tmp")
    assert workloads.known_workloads() == ("contract",)
